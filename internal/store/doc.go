// Package store owns PostgreSQL access for froodbase-api and
// froodbase-dreamer.
//
// It opens the pgx pool, embeds and applies the goose migrations under
// migrations/ (forward-only) followed by River's schema, and inserts River
// jobs. It owns the slice 1 record tables and their row-level security: every
// write and read runs in a transaction with the caller's areas set in the
// app.caller_areas session variable, as the non-owning service role the
// policies apply to. The writer (Contribute, UpdateEntity, UpdateAssertion,
// LinkEvidence) writes records, revision snapshots, audit events, support
// events and the index_record job together; revisions, audit events and
// support events are append-only. Queries are generated by sqlc into gen/
// (exempt from the boundary rule) from queries/ and the migrations.
//
// It holds no domain rules and decides no authorisation: who holds which
// areas comes from the caller, validity and support projection from
// internal/domain, the only package in the module it imports besides
// store/jobs. The test helper lives in store/storetest.
package store
